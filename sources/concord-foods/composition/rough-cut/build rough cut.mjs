// Builds the full-length rough cut from "film parts.js".
// Each part uses its own render when its status is "draft" or "approved", otherwise its
// placeholder slice from renders/rough cut placeholders.mp4. Writes renders/rough cut.mp4
// and "rough cut/chapters.js" (the chapter times the review page reads).
// Run from anywhere:  node "<path to v01>/rough cut/build rough cut.mjs"
import { createRequire } from "node:module";
import { execFileSync } from "node:child_process";
import { existsSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const renders = join(here, "..", "renders");
const require = createRequire(import.meta.url);
const parts = require(join(here, "film parts.js"));

const placeholders = join(renders, "rough cut placeholders.mp4");
if (!existsSync(placeholders)) throw new Error("Missing " + placeholders + ". Render the placeholder composition first (see index.html).");

const probe = (file) =>
  parseFloat(execFileSync("ffprobe", ["-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", file]).toString().trim());

const inputs = [];
const chapters = [];
let phStart = 0; // where this part sits in the placeholder render (storyboard timing)
let filmT = 0; // where this part sits in the rough cut
for (const part of parts) {
  const phLen = part.frames.reduce((s, f) => s + f.dur, 0);
  const useRender = part.status !== "placeholder" && part.render;
  let len;
  const frames = [];
  if (useRender) {
    const file = join(renders, part.render);
    if (!existsSync(file)) throw new Error(`Part ${part.id}: render not found: ${file}`);
    len = probe(file);
    inputs.push(["-i", file]);
    for (const f of part.frames) frames.push({ id: f.id, name: f.name, eyebrow: f.eyebrow, start: +(filmT + f.at).toFixed(2) });
  } else {
    len = phLen;
    inputs.push(["-ss", String(phStart), "-t", String(phLen), "-i", placeholders]);
    let t = 0;
    for (const f of part.frames) { frames.push({ id: f.id, name: f.name, eyebrow: f.eyebrow, start: +(filmT + t).toFixed(2) }); t += f.dur; }
  }
  chapters.push({ id: part.id, name: part.name, step: part.step, status: useRender ? part.status : "placeholder",
    note: part.note || "", start: +filmT.toFixed(2), end: +(filmT + len).toFixed(2), frames });
  phStart += phLen;
  filmT += len;
}

const n = inputs.length;
const filter = inputs.map((_, i) => `[${i}:v]scale=1920:1080:force_original_aspect_ratio=decrease,pad=1920:1080:(ow-iw)/2:(oh-ih)/2,fps=30,format=yuv420p,setsar=1[v${i}]`).join(";") +
  ";" + inputs.map((_, i) => `[v${i}]`).join("") + `concat=n=${n}:v=1:a=0[out]`;
const out = join(renders, "rough cut.mp4");
execFileSync("ffmpeg", ["-y", "-v", "error", ...inputs.flat(), "-filter_complex", filter, "-map", "[out]",
  "-c:v", "libx264", "-preset", "veryfast", "-crf", "23", "-movflags", "+faststart", out], { stdio: "inherit" });

writeFileSync(join(here, "chapters.js"),
  "// Generated by build rough cut.mjs. Do not edit by hand; edit film parts.js and rebuild.\n" +
  "var ROUGH_CUT = " + JSON.stringify({ built: new Date().toISOString().slice(0, 16).replace("T", " "), total: +filmT.toFixed(2), parts: chapters }, null, 1) + ";\n");
console.log(`Rough cut built: ${out} (${filmT.toFixed(1)} s, ${n} parts)`);
